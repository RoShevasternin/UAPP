package com.rbxhubpro.rohumex.businesModule.backend

// ═══════════════════════════════════════════════════════════════════════════
// Bt — тип механики. СЛОВАРЬ ОБЩИЙ на все 30 приложений (APK_INTEGRATION.md,
// правка 4): по нему сравнивают «какая механика лучше держит людей» по всему
// парку, поэтому значения строк ФИКСИРОВАНЫ и переименованию не подлежат.
//
// ⚠️ НОВЫЙ ЭЛЕМЕНТ НЕ ДОБАВЛЯТЬ САМОВОЛЬНО. Дока: «если механика не ложится
// ни в один тип — не выдумывать новый на ходу, прислать нам, добавим в словарь
// вместе с версией». Свободный bt = 30 несравнимых словарей, то есть ровно то,
// ради чего таблица и заведена. Появился новый тип у них — добавляем сюда
// константу, и только тогда используем.
//
// Зачем enum, а не строки по коду: опечатка в "catalog" не ловится ничем и
// молча создаёт второй тип механики в отчётах. Здесь она не компилируется.
// ═══════════════════════════════════════════════════════════════════════════

enum class Bt(val key: String) {

    /** вопрос → ответ */
    QUIZ("quiz"),

    /** выбрать клетку / стереть */
    GRID("grid"),

    /** раскрыть / найти */
    REVEAL("reveal"),

    /** одно действие → приз */
    SPIN("spin"),

    /** таймер / кликер */
    TAP("tap"),

    /** ежедневная награда */
    DAILY("daily"),

    /** набор задач → общий приз */
    QUEST("quest"),

    /** выдача монет без игры */
    GIFT("gift"),

    /** утилита (ради неё ставят приложение) */
    TOOL("tool"),

    /** контентные списки */
    CATALOG("catalog"),

    /** экран-концентратор: хаб, возврат из веба */
    HUB("hub"),
    ;

    override fun toString(): String = key
}