package com.racing.funtols.game.controller

// ═════════════════════════════════════════════════════════════════════════════
//  PlateController — логіка пазла "склади номерні таблички".
//
//  Дошка: plateCount рядів × 2 слоти = pieceCount половинок.
//  Слоти нумеруються зліва направо, зверху вниз:
//
//      слот 0 | слот 1      ← ряд 0
//      слот 2 | слот 3      ← ряд 1
//      слот 4 | слот 5      ← ряд 2
//      слот 6 | слот 7      ← ряд 3
//
//  Половинки нумеруються так, як лежать в атласі (listPlate):
//      piece 0 + piece 1 = табличка 1  (plate_1 + plate_2)
//      piece 2 + piece 3 = табличка 2  (plate_3 + plate_4)
//      ...
//  Тобто ПАРНА половинка — завжди ліва, НЕПАРНА — права до неї.
//
//  Ряд зібраний, якщо зліва парна половинка, а справа — наступна за нею.
//  ПОРЯДОК РЯДІВ НЕ ВАЖЛИВИЙ: "RACING" може стояти в будь-якому ряду,
//  бо гравець ніяк не може знати, в якому саме ряду табличка "має" бути.
// ═════════════════════════════════════════════════════════════════════════════

class PlateController(private val plateCount: Int = 4) {

    // ------------------------------------------------------------------------
    // Board
    // ------------------------------------------------------------------------
    // slots[i] — індекс половинки, яка зараз лежить у слоті i
    private val slots = MutableList(plateCount * 2) { it }

    // ------------------------------------------------------------------------
    // State
    // ------------------------------------------------------------------------
    // Ввід заблоковано, поки в'юшка програє анімацію обміну
    var isLocked = false
        private set

    val pieceCount get() = plateCount * 2
    val rowCount   get() = plateCount

    val isWin get() = (0 until rowCount).all { isRowCorrect(it) }

    // ------------------------------------------------------------------------
    // Callback
    // ------------------------------------------------------------------------
    var onSwap : (Int, Int) -> Unit = { _, _ -> }  // слоти, вміст яких помінявся
    var onWin  : () -> Unit         = {}

    // ------------------------------------------------------------------------
    // API
    // ------------------------------------------------------------------------

    /** Яка половинка зараз у слоті [slot] */
    fun pieceAt(slot: Int) = slots[slot]

    /** У якому слоті зараз половинка [piece] */
    fun slotOf(piece: Int) = slots.indexOf(piece)

    /** Чи зібрана табличка в ряду [row] */
    fun isRowCorrect(row: Int): Boolean {
        val left  = slots[row * 2]
        val right = slots[row * 2 + 1]
        return left % 2 == 0 && right == left + 1
    }

    /** Нова роздача: перемішати так, щоб пазл не був зібраний одразу */
    fun newGame() {
        do { slots.shuffle() } while (isWin)
        isLocked = false
    }

    /** Поміняти місцями вміст двох слотів (драг однієї половинки на іншу) */
    fun swap(slotA: Int, slotB: Int) {
        if (isLocked)       return
        if (slotA == slotB) return

        val tmp = slots[slotA]
        slots[slotA] = slots[slotB]
        slots[slotB] = tmp

        isLocked = true
        onSwap(slotA, slotB)
    }

    /** В'юшка викликає, коли анімація обміну завершилась */
    fun onSwapFinished() {
        isLocked = false
        if (isWin) onWin()
    }
}