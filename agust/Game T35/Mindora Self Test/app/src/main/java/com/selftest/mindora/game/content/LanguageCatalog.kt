package com.selftest.mindora.game.content

// ═════════════════════════════════════════════════════════════════════════════
//  LanguageCatalog — список мов у порядку макета.
//
//  ПОРЯДОК = ІНДЕКС ПРАПОРА. Прапори лежать в атласі як lang_1..lang_10 і
//  зібрані в SpriteUtil.listLangFlag тим самим порядком, тож окремої мапи
//  «мова → прапор» не треба: позиція в ALL і є індексом. Додаєш мову —
//  додаєш прапор під наступним номером, і більше нічого.
//
//  ⚠️ ПЕРЕМИКАЧ, А НЕ ПЕРЕКЛАД. Вибір поки лише зберігається й показується на
//  екрані Settings; жодного рядка інтерфейсу він не міняє. Тому Entry не має
//  ні локалі, ні посилання на файл перекладу — вони з'являться тоді, коли
//  з'явиться сам переклад.
// ═════════════════════════════════════════════════════════════════════════════
object LanguageCatalog {

    data class Entry(
        /** Зберігається в PlayerData — міняти не можна, інакше вибір злетить. */
        val id  : String,
        /**
         * Назва мови в списку.
         *
         * ⚠️ АНГЛІЙСЬКОЮ, А НЕ САМОЮ МОВОЮ, ЯК У МАКЕТІ — через шрифт, не
         * через задум. MSDF-атласи Montserrat зібрані на ~187 гліфів базової
         * латиниці: немає ні ієрогліфів (日本語 · 한국어 · 中文), ні навіть
         * діакритики (ñ у Español, ê у Português, ç у Français). Шість назв
         * із десяти малювались би порожніми.
         *
         * Коли шрифти перегенерують із ширшим набором — правиться лише цей
         * список, більше ніде назви не зашиті.
         */
        val name: String,
    )

    val ALL: List<Entry> = listOf(
        Entry("en", "English"),
        Entry("es", "Spanish"),
        Entry("pt", "Portuguese"),
        Entry("fr", "French"),
        Entry("de", "German"),
        Entry("it", "Italian"),
        Entry("ja", "Japanese"),
        Entry("ko", "Korean"),
        Entry("zh", "Chinese"),
        Entry("hi", "Hindi"),
    )

    val DEFAULT: Entry = ALL.first()

    /** Невідомий id (стерли мову з каталогу) → дефолт, а не краш. */
    fun byId(id: String): Entry = ALL.firstOrNull { it.id == id } ?: DEFAULT

    fun indexOf(id: String): Int = ALL.indexOfFirst { it.id == id }.coerceAtLeast(0)
}
